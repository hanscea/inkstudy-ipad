import {createRequire} from 'node:module';
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';

const require = createRequire(import.meta.url);
const source = new URL('../ThirdParty/Spectral/spectral.cjs', import.meta.url);
const sourceSHA256 = 'dbaa1a8b44d2c734b48b6d44777b1f182c9740e9220d2cbded02002c8e6d271a';
if (createHash('sha256').update(readFileSync(source)).digest('hex') !== sourceSHA256) {
  throw new Error('Spectral.js source differs from the reviewed version');
}
const spectral = require(source.pathname);
const palette = ['#e53166', '#fcd200', '#3375da'];
const colors = palette.map(hex => new spectral.Color(hex));
const divisions = 64, side = divisions + 1;
const bytes = Buffer.alloc(side * side * 3);
for (let r = 0; r <= divisions; r++) {
  for (let y = 0; y <= divisions; y++) {
    const b = Math.max(0, divisions - r - y);
    const result = spectral.mix([colors[0], r], [colors[1], y], [colors[2], b]).toGamut().sRGB;
    result.forEach((channel, c) => { bytes[(r * side + y) * 3 + c] = Math.round(channel); });
  }
}
const destination = new URL('../Core/Sources/InkStudyCore/Resources/pigment-spectral-v2.rgb', import.meta.url);
writeFileSync(destination, bytes);
const rows = [];
for (let i = 0; i < bytes.length; i += 24) rows.push('        ' + [...bytes.subarray(i, i + 24)].join(', ') + ',');
const compiled = '// Generated by scripts/generate-pigment-lut.mjs. Do not edit manually.\n'
  + '// Spectral.js is MIT licensed; see Resources/SPECTRAL_LICENSE.txt.\n'
  + 'enum SpectralLookupTable {\n    static let bytes: [UInt8] = [\n' + rows.join('\n') + '\n    ]\n}\n';
writeFileSync(new URL('../Core/Sources/InkStudyCore/SpectralLookupTable.swift', import.meta.url), compiled);
console.log(JSON.stringify({model: 'spectral-wet-v2', sourceSHA256, divisions, palette,
  bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex')}, null, 2));
